/**
 * Escape HTML special characters to prevent XSS/HTML injection.
 * Use for all user-supplied values interpolated into HTML email bodies.
 */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;')
}
